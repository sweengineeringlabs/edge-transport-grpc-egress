"""scripts/list_file_dispositions.py: where every source file of the old tree went."""
import os
import re
import subprocess
import sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = sys.argv[1] if len(sys.argv) > 1 else "v0.7.0"


def git(*a):
    return subprocess.run(["git", "-C", REPO] + list(a), capture_output=True, text=True, encoding="utf-8", errors="replace").stdout


def rs_files(rev):
    return [f for f in git("ls-tree", "-r", "--name-only", rev).split("\n") if f.endswith(".rs") and "/src/" in f]


old = rs_files(BASE)
new = set(rs_files("HEAD"))

# Follow every old file commit by commit: a rename moves it, a deletion ends it.
current = {f: f for f in old}  # old path -> path now
ended = {}  # old path -> the commit that removed it
commits = git("rev-list", "--reverse", "--first-parent", "%s..HEAD" % BASE).split()
for commit in commits:
    for line in git("diff-tree", "-r", "-M30%", "--name-status", "--first-parent", "-m", commit).split(chr(10)):
        parts = line.split(chr(9))
        if len(parts) == 3 and parts[0].startswith("R"):
            for k, v in current.items():
                if v == parts[1] and k not in ended:
                    current[k] = parts[2]
        elif len(parts) == 2 and parts[0] == "D":
            for k, v in current.items():
                if v == parts[1] and k not in ended:
                    ended[k] = commit

rows = []
for f in sorted(old):
    if f in ended:
        subject = git("log", "-1", "--format=%h %s", ended[f]).strip()
        rows.append((f, "removed or merged", subject))
    elif current[f] == f:
        changed = subprocess.run(["git", "-C", REPO, "diff", "--quiet", BASE, "HEAD", "--", f]).returncode != 0
        rows.append((f, "stays" + (" (edited)" if changed else " (unchanged)"), ""))
    else:
        rows.append((f, "moves", current[f]))

counts = {}
for _, d, _ in rows:
    kind = d.split(" (")[0]
    counts[kind] = counts.get(kind, 0) + 1

out = ["# Where every source file of %s went\n\n" % BASE,
       "Generated by `scripts/list_file_dispositions.py %s` (git rename detection at 50 percent; a file that was merged into another shows as removed, with the commit that removed it). %d files.\n\n" % (BASE, len(rows)),
       "| Disposition | Files |\n|---|---|\n"]
for k, v in sorted(counts.items()):
    out.append("| %s | %d |\n" % (k, v))
out.append("\n| Old file | Disposition | New file, or the commit that removed it |\n|---|---|---|\n")
for f, d, w in rows:
    out.append("| `%s` | %s | %s |\n" % (f, d, ("`%s`" % w) if d == "moves" else w))
open(os.path.join(REPO, "scm", "docs", "file-dispositions.md"), "w", encoding="utf-8", newline="\n").write("".join(out))
print(len(rows), counts)
