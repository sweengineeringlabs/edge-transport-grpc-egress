"""Usage: python scripts/list_removed_tests.py [BASE_REVISION]  (default: the commit before #38)

Lists the test functions that existed at BASE_REVISION and exist nowhere at HEAD, with a reason per
group, and writes scm/docs/removed-tests.md (acceptance criterion: every removed test is named)."""
import os
import re
import subprocess
import sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = sys.argv[1] if len(sys.argv) > 1 else "58ae93a"  # before #38


def git(*a):
    return subprocess.run(["git", "-C", REPO] + list(a), capture_output=True, text=True, encoding="utf-8", errors="replace").stdout


FN = re.compile(r"(?:#\[(?:tokio::)?test[^\]]*\]\s*(?:///[^\n]*\n\s*|#\[[^\]]*\]\s*)*)(?:pub\s+)?(?:async\s+)?fn\s+(\w+)")


def names(text):
    return set(FN.findall(text))


def files_at(rev):
    out = git("ls-tree", "-r", "--name-only", rev).split("\n")
    return [f for f in out if f.endswith(".rs") and ("/tests/" in f or "/src/" in f)]


old = {}
for f in files_at(BASE):
    text = git("show", "%s:%s" % (BASE, f))
    n = names(text)
    if n:
        old[f] = (n, text)

new_names = set()
for f in files_at("HEAD"):
    new_names |= names(git("show", "HEAD:%s" % f))

def deleted_by(path):
    """The subject of the commit after BASE that deleted `path`, or None while the file still exists."""
    out = git("log", "--diff-filter=D", "-1", "--format=%h %s", "%s..HEAD" % BASE, "--", path).strip()
    return out or None


groups = {}
for f, (n, text) in sorted(old.items()):
    gone = sorted(x for x in n if x not in new_names)
    if not gone:
        continue
    commit = deleted_by(f)
    if commit:
        reason = "File deleted by: " + commit
    else:
        reason = "Inline or edited tests of files that still exist: the behaviour is re-tested through the public API, or the subject was removed (see the pull requests #38 to #42)"
    groups.setdefault(reason, []).append((f, gone))

total = sum(len(g) for v in groups.values() for _, g in v)
out = ["# Test functions of the old tree that no longer exist\n",
       "Generated by `scripts/list_removed_tests.py` from `%s` to `HEAD`: every test function name that appeared in the old tree and appears nowhere in the new one. A function that only moved or was renamed together with its file is not listed when its name still exists.\n" % BASE,
       "**%d test functions** in %d files.\n" % (total, sum(len(v) for v in groups.values()))]
for reason, items in groups.items():
    out.append("\n## %s\n" % reason)
    for f, gone in items:
        out.append("\n`%s`: %s\n" % (f, ", ".join("`%s`" % g for g in gone)))
open(REPO + "/scm/docs/removed-tests.md", "w", encoding="utf-8", newline="\n").write("".join(out))
print(total, "removed names")
